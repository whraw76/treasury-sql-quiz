"""Read-only checks for the audit table's effective database permissions."""


def verify_audit_permissions(conn):
    # Look up the table without granting readers access to its schema.
    table = conn.execute(
        """SELECT c.oid, c.relowner, n.oid, c.relrowsecurity FROM pg_class c
           JOIN pg_namespace n ON n.oid = c.relnamespace
           WHERE n.nspname = 'quiz_audit' AND c.relname = 'events' AND c.relkind = 'r'"""
    ).fetchone()
    if table is None:
        raise RuntimeError("Apply sql/audit_log.sql before deploying this version.")
    table_id, owner_id, schema_id, rls_enabled = table
    if not rls_enabled:
        raise RuntimeError("Enable row-level security on the audit table.")
    for role in ("treasury_reader", "treasury_writer"):
        flags = conn.execute(
            "SELECT rolsuper, rolcreaterole, rolcreatedb, rolbypassrls FROM pg_roles WHERE rolname = %s",
            (role,),
        ).fetchone()
        if flags != (False, False, False, False):
            raise RuntimeError(f"{role} must be a restricted role.")
        powerful = conn.execute(
            "SELECT pg_has_role(%s, %s, 'MEMBER'), has_schema_privilege(%s, %s, 'CREATE')",
            (role, owner_id, role, schema_id),
        ).fetchone()
        if any(powerful):
            raise RuntimeError(f"{role} must not own or administer the audit schema.")
        unsafe = conn.execute(
            """SELECT has_table_privilege(%s, %s, 'SELECT,UPDATE,DELETE,TRUNCATE,TRIGGER'),
                      has_any_column_privilege(%s, %s, 'SELECT,UPDATE')""",
            (role, table_id, role, table_id),
        ).fetchone()
        if any(unsafe):
            raise RuntimeError(f"{role} must not read, edit or delete audit history.")
    if conn.execute("SELECT has_any_column_privilege('treasury_reader', %s, 'INSERT')", (table_id,)).fetchone()[0]:
        raise RuntimeError("The query reader must not insert audit events.")
    for column in ("id", "actor_id", "action", "outcome", "sql_text", "quiz_id", "details"):
        allowed, grantable = conn.execute(
            """SELECT has_column_privilege('treasury_writer', %s, %s, 'INSERT'),
                      has_column_privilege('treasury_writer', %s, %s, 'INSERT WITH GRANT OPTION')""",
            (table_id, column, table_id, column),
        ).fetchone()
        if not allowed or grantable:
            raise RuntimeError("The writer needs non-delegable INSERT access to event fields.")
    if conn.execute("SELECT has_column_privilege('treasury_writer', %s, 'occurred_at', 'INSERT')", (table_id,)).fetchone()[0]:
        raise RuntimeError("Audit timestamps must be generated by PostgreSQL.")
    if not conn.execute("SELECT has_schema_privilege('treasury_writer', %s, 'USAGE')", (schema_id,)).fetchone()[0]:
        raise RuntimeError("The writer needs USAGE on the audit schema.")
